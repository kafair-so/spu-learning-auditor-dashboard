import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const src=fs.readFileSync('audit-evidence.js','utf8');
const start=src.indexOf('  const actionableIssues=');
const end=src.indexOf('  const fixSummary=',start);
assert.ok(start>0&&end>start,'actionable issue function found');
const context={};
vm.runInNewContext(src.slice(start,end)+'\nglobalThis.actionableIssues=actionableIssues;',context);
const issues=context.actionableIssues;
const video={session:2,label:'วิดีโอบันทึกการสอนล่วงหน้า',status:'fail',detail:'พบลิงก์วิดีโอภายนอก 2 รายการ · เวลาที่อ่านและนับได้ 47:38 / 1:30:00 · ไม่นับคลิปที่ไม่พบเวลาหรือเปิดไม่ได้'};
const vod1={auditSession:2,kind:'video',mediaStatus:'duration_read',linkStatus:'external',durationSeconds:1217,countingEligible:true,reviewExcluded:false};
const vod2={...vod1,durationSeconds:1641};
const recordings=[{auditSession:2,kind:'recording',linkStatus:'skipped_recording',mediaStatus:''},{auditSession:2,kind:'recording',linkStatus:'skipped_recording',mediaStatus:'link_error'}];
const keys=(x,rows)=>Array.from(issues(x,rows),i=>i.key);
assert.deepEqual(keys(video,[vod1,vod2,...recordings]),['video-duration'],'BUS431 valid VOD, skipped recordings: duration only');
assert.deepEqual(keys(video,[...recordings]),['video-duration'],'recording errors are not VOD access errors');
assert.deepEqual(keys(video,[vod1,{...vod2,mediaStatus:'access_denied'},...recordings]),['video-access','video-duration'],'actual VOD access issue and insufficient duration');
assert.deepEqual(keys(video,[vod1,{...vod2,mediaStatus:'link_error'}]),['video-access','video-duration'],'real VOD link error');
assert.deepEqual(keys(video,[vod1,{...vod2,auditSession:3,mediaStatus:'link_error'}]),['video-duration'],'other sessions do not leak link errors');
assert.deepEqual(keys(video,[]),['video-duration'],'no media inspection is not proof of broken links');
assert.ok(issues({...video,detail:'ลิงก์วิดีโอเปิดไม่ได้'},[{...vod2,mediaStatus:'link_unavailable'}]).some(x=>x.label==='ลิงก์วิดีโอเปิดปลายทางไม่ได้'));
assert.ok(issues({session:2,label:'Podcast',detail:'ติดสิทธิ์ผู้ให้บริการ'},[]).some(x=>x.key==='podcast-access'),'non-video access rule intact');
assert.ok(fs.readFileSync('ui-i18n.js','utf8').includes('"ลิงก์วิดีโอเปิดปลายทางไม่ได้":"Video link destination inaccessible"'));
assert.ok(fs.readFileSync('audit-evidence.html','utf8').includes('audit-evidence.js?v=20261120videoissues1'));
console.log('BUS431 media-status classification and issue wording regression tests passed');
