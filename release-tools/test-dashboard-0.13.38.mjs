import assert from 'node:assert/strict';
import '../build/dashboard-0.13.38/gr-instructor-context.js';
import {normalizeCentralJob} from '../build/dashboard-0.13.38/central-worker-contract.js';
const {evaluate}=globalThis.SpuGrInstructorContext;
const region=(text,images=[],section='s1',title='Week 1',links=[])=>({text,images,section,title,links});
const image=(label='',others={})=>({candidate:true,label,...others});
let e=evaluate([region('Instructor\nSECTION D400 Ms. Luckana Santinarong\nEmail: teacher@example.edu', [image('')])],'');
assert.equal(e.reviewStatus,'uncertain_evidence');assert.equal(e.hasInstructorPhoto,false);assert.equal(e.contactComplete,true);
e=evaluate([region('Instructor\nSECTION D400 Ms. Luckana Santinarong\nEmail: teacher@example.edu',[image('Instructor portrait')])],'');
assert.equal(e.reviewStatus,'evidence_found');assert.equal(e.identityComplete,true);
e=evaluate([region('อาจารย์ผู้สอน\nวีรภัทร สุธีรางกูร'),region('ติดต่อสอบถามได้ที่ Line ID : kanomdesign',[image('')])],'นายวีรภัทร สุธีรางกูร');
assert.equal(e.reviewStatus,'uncertain_evidence');assert.equal(e.expectedInstructorMatches.length,1);assert.equal(e.contactComplete,true);
e=evaluate([region('Line Group QR Code and Instructors',[image('',{qr:true})])],'');
assert.equal(e.reviewStatus,'uncertain_evidence');assert.equal(e.contactComplete,true);assert.equal(e.identityComplete,false);
e=evaluate([region('Instructor\nQR Code',[image('')])],'');
assert.notEqual(e.reviewStatus,'evidence_found');assert.equal(e.contactComplete,false);
e=evaluate([region('Video on demand Week 2\nLecture by unrelated person',[image('')],'s2','Week 2'),region('Facebook group',[],'s3','Week 3')],'Expected Teacher');
assert.equal(e.reviewStatus,'incomplete_evidence');assert.equal(e.names.length,0);
e=evaluate([region('Instructor\nMr. John Smith',[image('Instructor portrait')],'s1'),region('Email: teacher@example.edu',[],'s2')],'John Smith');
assert.equal(e.contactComplete,false);assert.notEqual(e.reviewStatus,'evidence_found');
e=evaluate([region('Course Outline\nWelcome',[image('')])],'Expected Teacher');
assert.equal(e.reviewStatus,'incomplete_evidence');
const job={job_id:'j',course_id:'21341',course_group:'GR',criteria_mode:'legacy_12569',semester_code:'1/2569',instructor_names:['John Smith']};
assert.equal(normalizeCentralJob(job).instructors,'John Smith');
assert.equal(normalizeCentralJob({...job,course_group:'GS',criteria_mode:'current'}).instructors,undefined);
console.log('GR instructor regression fixtures passed');
